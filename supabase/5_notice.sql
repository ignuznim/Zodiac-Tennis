-- 십이지 테니스 · 5. 공지사항: notes for every player (updates, events), shown from the 공지사항 button on the home screen.
-- Run in Supabase: SQL Editor -> New query -> paste all of it -> Run.
-- Safe to run again: it only adds what is missing and replaces its own rules; notes already written stay.
--
-- Writing a note: Table Editor -> notices -> Insert row. Fill in
--   kind     update (업데이트) · event (이벤트) · info (안내)
--   title    one line, up to 40 letters
--   body     the text; press Enter for a new line (up to 2000 letters)
--   pinned   true keeps it at the top
--   ends_at  optional: after this time the note disappears by itself (good for events)
--   visible  false hides it without deleting it
-- The newest note lights a red dot on the 공지사항 button until each player opens it.

create table if not exists public.notices (
  id         bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  kind       text not null default 'update',
  title      text not null,
  body       text not null default '',
  pinned     boolean not null default false,
  visible    boolean not null default true,
  ends_at    timestamptz
);
alter table public.notices drop constraint if exists notices_kind_check;
alter table public.notices add constraint notices_kind_check check (kind in ('update', 'event', 'info'));
alter table public.notices drop constraint if exists notices_title_check;
alter table public.notices add constraint notices_title_check check (char_length(title) between 1 and 40);
alter table public.notices drop constraint if exists notices_body_check;
alter table public.notices add constraint notices_body_check check (char_length(body) <= 2000);
create index if not exists notices_recent on public.notices (pinned desc, created_at desc);

-- Everyone may read the notes that are showing; only you (in the dashboard) write them
alter table public.notices enable row level security;
drop policy if exists "read notices" on public.notices;
create policy "read notices" on public.notices for select to anon, authenticated
  using (visible and (ends_at is null or ends_at > now()));
revoke all on public.notices from anon, authenticated;
grant select on public.notices to anon, authenticated;

-- The first note, only when the table is still empty
insert into public.notices (kind, title, body)
select 'update', '1.9.3 업데이트',
  E'· 쉬움, 보통 난이도가 쉬워졌어요\n· 경기 방식 화면 맨 위에서 단식과 복식을 골라요\n· 뽑기를 5회, 10회씩 한 번에 할 수 있어요\n· 2:2 대전 방에서 팀을 보고 바꿀 수 있어요\n· 공지사항이 생겼어요'
where not exists (select 1 from public.notices);
